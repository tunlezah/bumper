"""TLS client contexts for the harness (stdlib ``ssl`` only)."""

import socket
import ssl
import threading
import warnings

VERSIONS = ["TLSv1", "TLSv1_1", "TLSv1_2", "TLSv1_3"]


def client_context(ca_file):
    """Normal client context: verify the chain against the Bumper CA.

    Hostname checking is off: certificates generated by create_certs list the
    host's own interfaces, and which name the harness dials is not what is
    under test here. The chain is still verified.
    """
    ctx = ssl.create_default_context(cafile=ca_file)
    ctx.check_hostname = False
    return ctx


def pinned_context(ca_file, version_name):
    """Client context that only offers one protocol version.

    ``@SECLEVEL=0`` lets OpenSSL 3 offer TLS 1.0/1.1 at all; without it the
    probe would fail on the client side and say nothing about the server.
    """
    version = getattr(ssl.TLSVersion, version_name)
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
    ctx.check_hostname = False
    ctx.load_verify_locations(cafile=ca_file)
    if version_name != "TLSv1_3":
        ctx.set_ciphers("DEFAULT:@SECLEVEL=0")
    with warnings.catch_warnings():
        # Python >= 3.12 warns that TLSv1/TLSv1_1 are deprecated. Offering
        # them is the whole point of the probe.
        warnings.simplefilter("ignore", DeprecationWarning)
        ctx.minimum_version = version
        ctx.maximum_version = version
    return ctx


_local_support = {}


def local_openssl_supports(version_name):
    """Can this interpreter's OpenSSL negotiate ``version_name`` with itself?

    Some distributions build OpenSSL without TLS 1.0/1.1. Then a "rejected"
    result from a probe would be a client limitation, not server behaviour,
    so the TLS-matrix test marks that probe xfail instead.
    """
    if version_name in _local_support:
        return _local_support[version_name]
    import os
    from . import config

    certs = config.TEST_CERTS_DIR
    server_ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    server_ctx.load_cert_chain(os.path.join(certs, "bumper.crt"), os.path.join(certs, "bumper.key"))
    ok = False
    try:
        if version_name != "TLSv1_3":
            server_ctx.set_ciphers("DEFAULT:@SECLEVEL=0")
        with warnings.catch_warnings():
            warnings.simplefilter("ignore", DeprecationWarning)
            server_ctx.minimum_version = getattr(ssl.TLSVersion, version_name)
            server_ctx.maximum_version = getattr(ssl.TLSVersion, version_name)
        client_ctx = pinned_context(os.path.join(certs, "ca.crt"), version_name)

        listener = socket.socket()
        listener.bind(("127.0.0.1", 0))
        listener.listen(1)
        port = listener.getsockname()[1]

        def serve():
            try:
                conn, _ = listener.accept()
                with server_ctx.wrap_socket(conn, server_side=True) as s:
                    s.recv(1)
            except (OSError, ssl.SSLError):
                pass

        t = threading.Thread(target=serve, daemon=True)
        t.start()
        try:
            with socket.create_connection(("127.0.0.1", port), timeout=5) as raw:
                with client_ctx.wrap_socket(raw) as s:
                    ok = s.version() == version_name.replace("_", ".")
                    s.sendall(b"x")
        except (OSError, ssl.SSLError):
            ok = False
        t.join(5)
        listener.close()
    except (ssl.SSLError, ValueError):
        ok = False
    _local_support[version_name] = ok
    return ok
